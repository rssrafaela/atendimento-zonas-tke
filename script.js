// ==========================================================
// NORMALIZAR TEXTO
// ==========================================================

function normalizeText(text) {
  return text
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .trim();
}


// ==========================================================
// PRIMEIRO NOME
// ==========================================================

function firstName(fullName) {

  if (!fullName || fullName === "A definir") {
    return "";
  }

  return fullName.split(" ")[0];
}


// ==========================================================
// LINK DO WHATSAPP
// ==========================================================

function createWhatsAppLink(person, zoneNumber) {

  if (!person.phone) {
    return "";
  }

  const name = firstName(person.name);

  const message =
    zoneNumber === "13"
      ? `Olá, ${name}! Sou cliente da TK Elevator e estou entrando em contato referente à Zona 13 - Escadas Rolantes e Esteiras.`
      : `Olá, ${name}! Sou cliente da TK Elevator e estou entrando em contato referente à Zona ${zoneNumber}.`;

  return `
    <a
      class="whatsapp-link"
      href="https://wa.me/55${person.phone}?text=${encodeURIComponent(message)}"
      target="_blank"
      rel="noopener noreferrer"
      title="Conversar pelo WhatsApp"
    >
      ${whatsappIcon()}

      <span>
        ${person.phoneFormatted}
      </span>
    </a>
  `;
}


