if (searchInput) {

  searchInput.addEventListener(
    "keydown",
    (event) => {

      if (
        event.key === "Enter"
      ) {

        event.preventDefault();

        performSearch();

      }

    }
  );

}


// ==========================================================
// MOSTRAR X QUANDO DIGITAR
// ==========================================================

if (searchInput) {

  searchInput.addEventListener(
    "input",
    () => {

      if (
        searchInput.value.trim()
      ) {

        if (clearSearch) {
          clearSearch.classList.add(
            "visible"
          );
        }

      } else {

        if (clearSearch) {
          clearSearch.classList.remove(
            "visible"
          );
        }

        if (searchResult) {
          searchResult.classList.remove(
            "visible"
          );
        }

        clearHighlights();

      }

    }
  );

}


// ==========================================================
// LIMPAR PESQUISA
// ==========================================================

if (clearSearch) {

  clearSearch.addEventListener(
    "click",
    () => {

      if (searchInput) {

        searchInput.value = "";

        searchInput.focus();

      }


      if (searchResult) {

        searchResult.innerHTML = "";

        searchResult.classList.remove(
          "visible"
        );

      }


      clearSearch.classList.remove(
        "visible"
      );


      clearHighlights();

    }
  );

}
