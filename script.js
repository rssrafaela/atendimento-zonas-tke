// ==========================================================
// BOTÃO VER TODOS OS BAIRROS
// ==========================================================

function activateNeighborhoodButtons() {

  const buttons =
    document.querySelectorAll(
      ".toggle-neighborhoods"
    );

  buttons.forEach((button) => {

    button.addEventListener(
      "click",
      () => {

        const section =
          button.closest(
            ".neighborhood-section"
          );

        if (!section) {
          return;
        }

        const expanded =
          section.classList.toggle(
            "expanded"
          );

        const zoneCard =
          button.closest(
            ".zone-card"
          );

        if (!zoneCard) {
          return;
        }

        const zoneNumber =
          zoneCard.dataset.zone;

        const zone =
          zones.find(
            (item) =>
              item.number === zoneNumber
          );

        if (!zone) {
          return;
        }

        if (expanded) {

          button.textContent =
            zone.neighborhoods.length === 1
              ? "Ocultar região"
              : "Ocultar bairros";

        } else {

          button.textContent =
            zone.neighborhoods.length === 1
              ? "Ver região"
              : "Ver todos os bairros";

        }

      }
    );

  });
}


