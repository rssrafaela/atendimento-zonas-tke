// ==========================================================
// ENCONTRAR ZONAS POR BAIRRO
// ==========================================================

function findZonesByNeighborhood(search) {

  const normalizedSearch =
    normalizeText(search);

  if (!normalizedSearch) {
    return [];
  }

  return zones.filter(
    (zone) => {

      return zone.neighborhoods.some(
        (neighborhood) => {

          const normalizedNeighborhood =
            normalizeText(
              neighborhood
            );

          return (
            normalizedNeighborhood ===
              normalizedSearch ||
            normalizedNeighborhood.includes(
              normalizedSearch
            )
          );

        }
      );

    }
  );
}


// ==========================================================
// BAIRRO REAL ENCONTRADO
// ==========================================================

function findMatchedNeighborhood(
  zone,
  search
) {

  const normalizedSearch =
    normalizeText(search);

  return zone.neighborhoods.find(
    (neighborhood) =>
      normalizeText(
        neighborhood
      ).includes(
        normalizedSearch
      )
  );
}


// ==========================================================
// MOSTRAR RESULTADO DA PESQUISA
// ==========================================================

function performSearch() {

  if (
    !searchInput ||
    !searchResult
  ) {
    return;
  }


  const search =
    searchInput.value.trim();


  clearHighlights();


  if (!search) {

    searchResult.innerHTML = `
      <div class="search-message error">
        Digite o nome de um bairro para pesquisar.
      </div>
    `;

    searchResult.classList.add(
      "visible"
    );

    return;
  }


  const foundZones =
    findZonesByNeighborhood(
      search
    );


  // ======================================================
  // NENHUMA ZONA
  // ======================================================

  if (
    foundZones.length === 0
  ) {

    searchResult.innerHTML = `
      <div class="search-message error">

        Não encontramos o bairro
        <strong>"${search}"</strong>
        na relação de atendimento.

        Verifique a escrita ou tente
        selecionar uma das sugestões.

      </div>
    `;

    searchResult.classList.add(
      "visible"
    );

    return;
  }


  // ======================================================
  // RESULTADOS
  // ======================================================

  const buttons =
    foundZones
      .map((zone) => {

        const neighborhood =
          findMatchedNeighborhood(
            zone,
            search
          );

        return `
          <button
            class="search-zone-button"
            type="button"
            data-target-zone="${zone.number}"
            data-target-neighborhood="${normalizeText(neighborhood)}"
          >

            <span class="search-zone-number">
              ZONA ${zone.number}
            </span>

            <span class="search-zone-info">

              <strong>
                ${neighborhood}
              </strong>

              <span>
                Ver responsáveis
              </span>

            </span>

          </button>
        `;

      })
      .join("");


  const message =
    foundZones.length === 1
      ? `Encontramos 1 zona para <strong>${search}</strong>:`
      : `O bairro <strong>${search}</strong> possui atendimento em ${foundZones.length} zonas. Selecione a desejada:`;


  searchResult.innerHTML = `

    <div
      class="search-message"
      style="margin-bottom:10px;"
    >
      ${message}
    </div>

    <div class="search-found">
      ${buttons}
    </div>

  `;


  searchResult.classList.add(
    "visible"
  );


  document
    .querySelectorAll(
      ".search-zone-button"
    )
    .forEach((button) => {

      button.addEventListener(
        "click",
        () => {

          goToZone(
            button.dataset.targetZone,
            button.dataset.targetNeighborhood
          );

        }
      );

    });


  // Se encontrou apenas uma zona,
  // já destaca automaticamente.

  if (
    foundZones.length === 1
  ) {

    const neighborhood =
      findMatchedNeighborhood(
        foundZones[0],
        search
      );

    highlightZone(
      foundZones[0].number,
      normalizeText(
        neighborhood
      )
    );

  }

}


// ==========================================================
// DESTACAR ZONA
// ==========================================================

function highlightZone(
  zoneNumber,
  neighborhood
) {

  clearHighlights();


  const card =
    document.getElementById(
      `zona-${zoneNumber}`
    );


  if (!card) {
    return;
  }


  card.classList.add(
    "highlight"
  );


  const section =
    card.querySelector(
      ".neighborhood-section"
    );


  if (section) {

    section.classList.add(
      "expanded"
    );


    const button =
      section.querySelector(
        ".toggle-neighborhoods"
      );


    if (button) {
      button.textContent =
        "Ocultar bairros";
    }


    const neighborhoodTag =
      section.querySelector(
        `[data-neighborhood="${neighborhood}"]`
      );


    if (neighborhoodTag) {

      neighborhoodTag.classList.add(
        "found-neighborhood"
      );

    }

  }

}


// ==========================================================
// IR PARA A ZONA
// ==========================================================

function goToZone(
  zoneNumber,
  neighborhood
) {

  highlightZone(
    zoneNumber,
    neighborhood
  );


  const card =
    document.getElementById(
      `zona-${zoneNumber}`
    );


  if (!card) {
    return;
  }


  card.scrollIntoView({
    behavior: "smooth",
    block: "center",
  });

}


