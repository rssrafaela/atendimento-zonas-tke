// ==========================================================
// CRIAR PESSOA
// ==========================================================

function createPerson(person, role, zoneNumber) {

  const roleClass =
    role === "SUPERVISOR"
      ? "supervisor"
      : "consultant";

  const pendingClass =
    person.name === "A definir"
      ? "pending"
      : "";

  return `
    <div class="zone-person ${roleClass}">

      <span class="role">
        ${role}
      </span>

      <strong class="person-name ${pendingClass}">
        ${person.name}
      </strong>

      ${
        person.phone || person.email
          ? `
            <div class="person-contact">

              ${createWhatsAppLink(person, zoneNumber)}

              ${createEmailLink(person)}

            </div>
          `
          : ""
      }

    </div>
  `;
}


