// ==========================================================
// BAIRROS
// ==========================================================

function createNeighborhoods(zone) {

  if (zone.special) {
    return createSpecialService();
  }

  const neighborhoods = zone.neighborhoods;

  // Zona sem bairros cadastrados
  if (neighborhoods.length === 0) {
    return `
      <div class="neighborhood-section">

        <div class="neighborhood-header">

          <span class="neighborhood-label">
            REGIÃO ATENDIDA
          </span>

        </div>

        <div class="neighborhood-preview">
          Atendimento específico
        </div>

      </div>
    `;
  }

  const preview =
    neighborhoods.slice(0, 6).join(" • ") +
    (neighborhoods.length > 6 ? "..." : "");

  const tags = neighborhoods
    .map(
      (neighborhood) => `
        <span
          data-neighborhood="${normalizeText(neighborhood)}"
        >
          ${neighborhood}
        </span>
      `
    )
    .join("");

  const word =
    neighborhoods.length === 1
      ? "região"
      : "bairros";

  return `
    <div class="neighborhood-section">

      <div class="neighborhood-header">

        <span class="neighborhood-label">
          ${
            neighborhoods.length === 1
              ? "REGIÃO ATENDIDA"
              : "BAIRROS ATENDIDOS"
          }
        </span>

        <span class="neighborhood-count">
          ${neighborhoods.length} ${word}
        </span>

      </div>

      <div class="neighborhood-preview">
        ${preview}
      </div>

      <div class="neighborhood-list">
        ${tags}
      </div>

      <button
        class="toggle-neighborhoods"
        type="button"
      >
        ${
          neighborhoods.length === 1
            ? "Ver região"
            : "Ver todos os bairros"
        }
      </button>

    </div>
  `;
}


